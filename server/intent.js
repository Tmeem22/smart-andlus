/* نفي صريح: «لا تسوي رسم» · «ما قلت لك تسوي تقرير» · «بدون رسم بياني» · «شيل الرسمة» */
const RX_NO_TOOL = /(?:لا|ما|مو|مب|مهوب)\s*(?:تسوي|تسوّي|ترسم|تعمل|تحط|تضيف|أبغى|ابغى|أبي|ابي|أريد|اريد|بغيت|طلبت|قلت|بديت)|بدون\s*(?:رسم|رسمة|مخطط|تقرير|جدول|صورة)|بلا\s*(?:رسم|رسمة|مخطط|تقرير)|الغ(?:ي|ِ)?\s*(?:الرسم|الرسمة|التقرير|المخطط)|شيل\s*(?:الرسم|الرسمة|التقرير|المخطط)/i;

/* ترتيب الطلاب ≠ أفضل مادة عند طالب واحد.
   بدون التفريق كان سؤال «وش أفضل مادة عند ابني» يرسم ترتيب طلاب المدرسة. */
const RX_RANK     = /(?:أفضل|افضل|أعلى|اعلى|أقوى|اقوى|أوائل|اوائل|ترتيب|متفوق|متفوقين|top)/i;
const RX_PEOPLE   = /(?:الطلاب|طلاب|طالب|الطالبات|طالبات|الفصل|الصف|المدرسة|الشعبة)/;
const RX_SUBJECTS = /(?:ماده|مادة|مواد|المواد|درجه|درجة|الدرجات|تخصص|منهج)/;

const RX_CHART  = /رسم|بياني|بيان|مخطط|رسمه|رسمة|chart|graph|قارن|مقارنة/i;
const RX_DONUT  = /حضور|غياب|مواظبة|دوام|attendance/i;
const RX_REPORT = /تقرير|كشف\s*كامل|كشف\s*شامل|report/i;

function intentFlags(msg){
  const t = String(msg == null ? '' : msg);
  if(RX_NO_TOOL.test(t)) return { chart:false, donut:false, report:false, top:false, negated:true };
  return {
    chart:  RX_CHART.test(t),
    donut:  RX_DONUT.test(t),
    report: RX_REPORT.test(t),
    top:    RX_RANK.test(t) && RX_PEOPLE.test(t) && !RX_SUBJECTS.test(t),
    negated:false,
  };
}

module.exports = { intentFlags };
